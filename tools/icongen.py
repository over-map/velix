#!/usr/bin/env python3
"""SVG → asset catalog: design/assets/lucide/*.svg and design/assets/glyphs/*.svg become template-rendered vector
imagesets (Assets.xcassets/VelixIcons), plus App/DesignSystem/Generated/Icon+Velix.swift. Strips the embedded
metadata blocks (they are most of each file). Usage: python3 tools/icongen.py"""
import json, re, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "App/Resources/Assets.xcassets/VelixIcons"
SWIFT = ROOT / "App/DesignSystem/Generated/Icon+Velix.swift"
# icons-extra: Lucide icons the design pages use but the handoff didn't export (lucide-static 0.460.0, the version
# the design pages load; ISC). glyphs-extra: Velix glyphs P2 draws inline but the handoff didn't export (metro,
# roundabout; paths copied from P2). Status-bar decorations (battery, signal, wifi, camera, flashlight) are left out.
SOURCES = [("icon", ROOT / "design/assets/lucide"), ("icon", ROOT / "tools/icons-extra"), ("glyph", ROOT / "design/assets/glyphs"),
           ("glyph", ROOT / "tools/glyphs-extra")]


def camel(name: str) -> str:
    parts = re.split(r"[-_ ]+", name)
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return {"repeat": "repeatIcon", "return": "returnIcon"}.get(out, out)


def main():
    if CATALOG.exists():
        shutil.rmtree(CATALOG)
    CATALOG.mkdir(parents=True)
    (CATALOG / "Contents.json").write_text(json.dumps({"info": {"author": "velix-icongen", "version": 1}}, indent=2) + "\n")
    cases = {"icon": [], "glyph": []}
    for kind, folder in SOURCES:
        for svg in sorted(folder.glob("*.svg")):
            text = re.sub(r"(?s)<metadata>.*?</metadata>", "", svg.read_text())
            text = re.sub(r'\s+xmlns:c2pa="[^"]*"', "", text)
            text = re.sub(r"<!--.*?-->\s*", "", text, flags=re.S)
            name = f"{kind}-{svg.stem}"
            d = CATALOG / f"{name}.imageset"
            d.mkdir()
            (d / f"{name}.svg").write_text(text)
            (d / "Contents.json").write_text(json.dumps({
                "images": [{"filename": f"{name}.svg", "idiom": "universal"}],
                "info": {"author": "velix-icongen", "version": 1},
                "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"},
            }, indent=2) + "\n")
            cases[kind].append((camel(svg.stem), name))
    lines = ["// Generated by tools/icongen.py from design/assets. Do not edit.", "import SwiftUI", "",
             "/// Lucide icons used by Velix (ISC licence), 24 pt grid, 2 pt stroke, template rendering.",
             "enum VelixIcon: String, CaseIterable, Sendable {"]
    lines += [f'    case {c} = "{n}"' for c, n in cases["icon"]] + ["}", "",
              "/// Velix glyphs: ride types, hazards, train, EuroVelo badge (same grid and stroke).",
              "enum VelixGlyph: String, CaseIterable, Sendable {"]
    lines += [f'    case {c} = "{n}"' for c, n in cases["glyph"]] + ["}", "", "extension Image {",
              "    init(velix icon: VelixIcon) { self.init(icon.rawValue, bundle: .main) }",
              "    init(velix glyph: VelixGlyph) { self.init(glyph.rawValue, bundle: .main) }", "}", ""]
    SWIFT.write_text("\n".join(lines))
    print(f"{len(cases['icon'])} icons, {len(cases['glyph'])} glyphs")


if __name__ == "__main__":
    main()
