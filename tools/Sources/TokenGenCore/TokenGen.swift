import Foundation

/// Turns design/velix-tokens.json (+ tools/TokenGen/overrides.json) into Swift sources and an asset-catalog
/// colour folder. Pure: `generate` returns file contents keyed by relative path, the executable writes them.
public enum TokenGen {
    public struct Output: Equatable {
        /// Relative path → file contents, Swift files under the Swift output folder.
        public var swift: [String: String] = [:]
        /// Relative path (inside the asset catalog) → file contents.
        public var assets: [String: String] = [:]
    }

    public enum Failure: Error, CustomStringConvertible {
        case missing(String)
        case badHex(String, String)
        public var description: String {
            switch self {
            case let .missing(k): "velix-tokens.json: missing \(k)"
            case let .badHex(k, v): "velix-tokens.json: \(k) has invalid colour \(v)"
            }
        }
    }

    /// PostScript names of the bundled fonts by family and weight (App/Resources/Fonts).
    static let postScript: [String: [Int: String]] = [
        "Familjen Grotesk": [500: "FamiljenGroteskRoman-Medium", 600: "FamiljenGroteskRoman-SemiBold", 700: "FamiljenGroteskRoman-Bold"],
        "Atkinson Hyperlegible": [400: "AtkinsonHyperlegible-Regular", 700: "AtkinsonHyperlegible-Bold"],
    ]

    public static func generate(tokens: Data, overrides: Data?) throws -> Output {
        guard var t = try JSONSerialization.jsonObject(with: tokens) as? [String: Any] else { throw Failure.missing("root") }
        if let overrides, let o = try JSONSerialization.jsonObject(with: overrides) as? [String: Any] {
            t = merge(t, o)
        }
        var out = Output()
        let version = ((t["meta"] as? [String: Any])?["version"] as? String) ?? "?"
        let header = "// Generated by tools/TokenGen from design/velix-tokens.json \(version). Do not edit.\n"
        out.assets["VelixColors/Contents.json"] = folderContents
        out.swift["Color+Velix.swift"] = try colors(t, header: header, assets: &out.assets)
        out.swift["Font+Velix.swift"] = try fonts(t, header: header)
        out.swift["Metrics+Velix.swift"] = try metrics(t, header: header, assets: &out.assets)
        return out
    }

    // MARK: Colours

    static func colors(_ t: [String: Any], header: String, assets: inout [String: String]) throws -> String {
        guard let colors = t["color"] as? [String: [String: Any]] else { throw Failure.missing("color") }
        var lines: [String] = []
        for name in colors.keys.sorted() {
            let c = colors[name]!
            guard let light = c["light"] as? String, let dark = c["dark"] as? String else { throw Failure.missing("color.\(name)") }
            try add(name, light, dark, use: c["use"] as? String, &lines, &assets)
            // Metro families: second line of a family (alt) and the ink on each.
            if let alt = c["alt"] as? String { try add("\(name)Alt", alt, alt, use: "Second line of the family", &lines, &assets) }
            if let ink = c["ink"] as? String { try add("\(name)Ink", ink, ink, use: "Text on \(name)", &lines, &assets) }
            if let ink = c["altInk"] as? String { try add("\(name)AltInk", ink, ink, use: "Text on \(name)Alt", &lines, &assets) }
        }
        if let palette = t["palette"] as? [String: Any] {
            for name in palette.keys.sorted() {
                guard let hex = palette[name] as? String, hex.hasPrefix("#") else { continue }
                try add("palette\(name.prefix(1).uppercased())\(name.dropFirst())", hex, hex, use: "Palette \(name)", &lines, &assets)
            }
        }
        return header + """
        import SwiftUI

        extension Color {
            /// Velix design tokens (asset catalog colours with Any / Dark appearances).
            enum velix {
        \(lines.joined(separator: "\n"))
            }
        }

        """
    }

    static func add(_ name: String, _ light: String, _ dark: String, use: String?, _ lines: inout [String],
                    _ assets: inout [String: String]) throws {
        let asset = "velix\(name.prefix(1).uppercased())\(name.dropFirst())"
        assets["VelixColors/\(asset).colorset/Contents.json"] = try colorset(light: light, dark: dark, key: name)
        if let use { lines.append("        /// \(use)") }
        lines.append("        static let \(name) = Color(\"\(asset)\", bundle: .main)")
    }

    static func rgb(_ hex: String, key: String) throws -> (String, String, String) {
        let h = hex.trimmingCharacters(in: .whitespaces).replacingOccurrences(of: "#", with: "")
        guard h.count == 6, let v = UInt32(h, radix: 16) else { throw Failure.badHex(key, hex) }
        func c(_ shift: UInt32) -> String { String(format: "%.3f", Double((v >> shift) & 0xFF) / 255) }
        return (c(16), c(8), c(0))
    }

    static func colorset(light: String, dark: String, key: String) throws -> String {
        func entry(_ hex: String, dark: Bool) throws -> String {
            let (r, g, b) = try rgb(hex, key: key)
            let appearance = dark ? #", "appearances" : [ { "appearance" : "luminosity", "value" : "dark" } ]"# : ""
            return #"    { "idiom" : "universal"\#(appearance), "color" : { "color-space" : "srgb", "components" : { "red" : "\#(r)", "green" : "\#(g)", "blue" : "\#(b)", "alpha" : "1.000" } } }"#
        }
        return """
        {
          "colors" : [
        \(try entry(light, dark: false)),
        \(try entry(dark, dark: true))
          ],
          "info" : { "author" : "velix-tokengen", "version" : 1 }
        }

        """
    }

    static let folderContents = """
    {
      "info" : { "author" : "velix-tokengen", "version" : 1 }
    }

    """

    // MARK: Type

    static func fonts(_ t: [String: Any], header: String) throws -> String {
        guard let fonts = t["font"] as? [String: [String: Any]] else { throw Failure.missing("font") }
        var cases: [String] = []
        for name in fonts.keys.sorted() {
            let f = fonts[name]!
            guard let family = f["family"] as? String, let weight = f["weight"] as? Int,
                  let size = (f["size"] as? NSNumber)?.doubleValue, let lh = (f["lineHeight"] as? NSNumber)?.doubleValue
            else { throw Failure.missing("font.\(name)") }
            guard let ps = postScript[family]?[weight] else { throw Failure.missing("bundled font \(family) \(weight)") }
            let trackingEm = Double(((f["tracking"] as? String) ?? "0").replacingOccurrences(of: "em", with: "")) ?? 0
            let tabular = (f["tabularNumbers"] as? Bool) ?? false
            let riding = ((f["dynamicType"] as? String) ?? "").contains("capped")
            let relative = relativeStyle(size: size)
            cases.append("""
                    /// \(family) \(weight), \(fmt(size))/\(fmt(lh)) pt\(trackingEm != 0 ? ", tracking \(fmt(trackingEm)) em" : "")\(tabular ? ", tabular figures" : "")\(riding ? ", riding (capped)" : "").
                    static let \(name) = VelixType(postScriptName: "\(ps)", size: \(fmt(size)), lineHeight: \(fmt(lh)), trackingEm: \(fmt(trackingEm)), tabularNumbers: \(tabular), riding: \(riding), relativeTo: .\(relative))
            """)
        }
        return header + """
        import SwiftUI

        extension VelixType {
        \(cases.joined(separator: "\n"))
        }

        extension Font {
            /// Velix type scale as SwiftUI fonts (size scales with Dynamic Type; use `.velixType(_:)` for line height,
            /// tracking and tabular figures).
            enum velix {
        \(fonts.keys.sorted().map { "        static var \($0): Font { VelixType.\($0).font }" }.joined(separator: "\n"))
            }
        }

        """
    }

    static func relativeStyle(size: Double) -> String {
        switch size {
        case 30...: "largeTitle"
        case 26 ..< 30: "title"
        case 21 ..< 26: "title2"
        case 18 ..< 21: "title3"
        case 16.5 ..< 18: "body"
        case 15.5 ..< 16.5: "callout"
        case 14 ..< 15.5: "subheadline"
        case 12.5 ..< 14: "footnote"
        default: "caption"
        }
    }

    // MARK: Spacing, radius, touch targets, elevation, motion

    static func metrics(_ t: [String: Any], header: String, assets: inout [String: String]) throws -> String {
        func values(_ key: String) throws -> [(String, Double)] {
            guard let d = t[key] as? [String: Any] else { throw Failure.missing(key) }
            return d.keys.sorted().compactMap { k in
                if let v = (d[k] as? [String: Any])?["value"] as? NSNumber { return (k, v.doubleValue) }
                if let v = d[k] as? NSNumber { return (k, v.doubleValue) }
                return nil
            }
        }
        let spacing = try values("spacing").sorted { $0.1 < $1.1 }
        let radius = try values("radius").sorted { $0.1 < $1.1 }
        let touch = try values("touchTarget")
        var elevation: [String] = []
        if let e = t["elevation"] as? [String: [String: Any]] {
            for name in e.keys.sorted() {
                func spec(_ mode: String) -> String {
                    guard let m = e[name]![mode] as? [String: Any] else { return "nil" }
                    let y = (m["y"] as? NSNumber)?.doubleValue, blur = (m["blur"] as? NSNumber)?.doubleValue
                    let opacity = (m["opacity"] as? NSNumber)?.doubleValue
                    let shadow = y.map { "VelixShadow(y: \(fmt($0)), blur: \(fmt(blur ?? 0)), opacity: \(fmt(opacity ?? 0)))" } ?? "nil"
                    var border = "nil"
                    if let hex = m["border"] as? String {
                        let asset = "velixElevation\(name.uppercased())\(mode.capitalized)Border"
                        assets["VelixColors/\(asset).colorset/Contents.json"] = try? colorset(light: hex, dark: hex, key: "elevation.\(name)")
                        border = "Color(\"\(asset)\", bundle: .main)"
                    }
                    return "VelixElevationSpec(shadow: \(shadow), border: \(border))"
                }
                elevation.append("        static let \(name) = VelixElevation(light: \(spec("light")), dark: \(spec("dark")))")
            }
        }
        var motion: [String] = []
        if let m = t["motion"] as? [String: [String: Any]] {
            for name in m.keys.sorted() {
                let d = (m[name]!["durationMs"] as? NSNumber)?.doubleValue ?? 250
                let curve = (m[name]!["curve"] as? String) ?? "easeOut"
                let use = (m[name]!["use"] as? String) ?? ""
                let rm = (m[name]!["reduceMotion"] as? String) ?? ""
                motion.append("        /// \(use). Reduce Motion: \(rm).")
                motion.append("        static let \(name) = VelixMotion(durationMs: \(fmt(d)), curve: \"\(curve)\")")
            }
        }
        return header + """
        import SwiftUI

        extension CGFloat {
            /// Spacing scale.
            enum velix {
        \(spacing.map { "        static let \($0.0): CGFloat = \(fmt($0.1))" }.joined(separator: "\n"))

                /// Corner radii.
                enum radius {
        \(radius.map { "            static let \($0.0): CGFloat = \(fmt($0.1))" }.joined(separator: "\n"))
                }

                /// Minimum hit targets (riding screens use `riding`).
                enum touch {
        \(touch.map { "            static let \($0.0): CGFloat = \(fmt($0.1))" }.joined(separator: "\n"))
                }
            }
        }

        enum VelixElevations {
        \(elevation.joined(separator: "\n"))
        }

        enum VelixMotions {
        \(motion.joined(separator: "\n"))
        }

        """
    }

    // MARK: Helpers

    static func fmt(_ v: Double) -> String {
        v == v.rounded() ? String(Int(v)) : String(format: "%g", v)
    }

    /// Deep merge; keys starting with "_" and "reason" in the overrides are documentation only.
    static func merge(_ base: [String: Any], _ over: [String: Any]) -> [String: Any] {
        var out = base
        for (k, v) in over where !k.hasPrefix("_") && k != "reason" {
            if let vd = v as? [String: Any], let bd = base[k] as? [String: Any] {
                out[k] = merge(bd, vd)
            } else if !(v is [String: Any]) {
                out[k] = v
            }
        }
        return out
    }
}
